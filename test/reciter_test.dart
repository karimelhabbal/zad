import 'package:flutter_test/flutter_test.dart';
import 'package:shared_preferences/shared_preferences.dart';
import 'package:zad/data/models/reciter.dart';
import 'package:zad/data/models/settings_models.dart';
import 'package:zad/data/repositories/local_store.dart';
import 'package:zad/data/repositories/settings_repository.dart';

/// The reciter catalogue is the contract between the UI and the audio CDN.
///
/// These tests pin the parts that would silently produce a dead play button:
/// the URL shape, the "verified only" rule, and the fallback when a persisted
/// id is no longer valid.
void main() {
  TestWidgetsFlutterBinding.ensureInitialized();

  group('QuranReciter', () {
    test('builds the documented surah-level CDN URL', () {
      const alafasy = QuranReciter(
        id: 'ar.alafasy',
        arabicName: 'مشاري راشد العفاسي',
        englishName: 'Mishary Rashid Alafasy',
      );
      expect(
        alafasy.surahAudioUrl(1),
        'https://cdn.islamic.network/quran/audio-surah/128/ar.alafasy/1.mp3',
      );
      expect(
        alafasy.surahAudioUrl(114),
        'https://cdn.islamic.network/quran/audio-surah/128/ar.alafasy/114.mp3',
      );
    });

    test('exposes a localised name', () {
      const reciter = QuranReciter(
        id: 'ar.test',
        arabicName: 'عربي',
        englishName: 'English',
      );
      expect(reciter.nameFor(isArabic: true), 'عربي');
      expect(reciter.nameFor(isArabic: false), 'English');
    });

    test('compares by id', () {
      const a = QuranReciter(id: 'ar.a', arabicName: 'أ', englishName: 'A');
      const b = QuranReciter(id: 'ar.a', arabicName: 'ب', englishName: 'B');
      const c = QuranReciter(id: 'ar.c', arabicName: 'أ', englishName: 'A');
      expect(a, b);
      expect(a.hashCode, b.hashCode);
      expect(a, isNot(c));
    });
  });

  group('QuranReciters catalogue', () {
    test('is not empty and every id is unique', () {
      expect(QuranReciters.all, isNotEmpty);
      final ids = QuranReciters.all.map((r) => r.id).toList();
      expect(ids.toSet().length, ids.length, reason: 'duplicate reciter id');
    });

    test('every entry has a CDN-shaped id and both display names', () {
      for (final reciter in QuranReciters.all) {
        expect(reciter.id, startsWith('ar.'));
        expect(reciter.arabicName.trim(), isNotEmpty, reason: reciter.id);
        expect(reciter.englishName.trim(), isNotEmpty, reason: reciter.id);
        expect(
          Uri.parse(reciter.surahAudioUrl(1)).host,
          'cdn.islamic.network',
          reason: reciter.id,
        );
      }
    });

    test('the default reciter is itself in the catalogue', () {
      expect(QuranReciters.isVerified(QuranReciters.defaultReciterId), isTrue);
      expect(QuranReciters.defaultReciter.id, QuranReciters.defaultReciterId);
      expect(QuranReciters.all, contains(QuranReciters.defaultReciter));
    });

    test('isVerified rejects unknown and null ids', () {
      expect(QuranReciters.isVerified(null), isFalse);
      expect(QuranReciters.isVerified(''), isFalse);
      // Verified live as 403 Forbidden on the CDN — must never be offered.
      expect(QuranReciters.isVerified('ar.husary'), isFalse);
      expect(QuranReciters.isVerified('ar.mahermuaiqly'), isFalse);
    });

    test('byId falls back to the default for anything unrecognised', () {
      expect(QuranReciters.byId(null).id, QuranReciters.defaultReciterId);
      expect(QuranReciters.byId('nope').id, QuranReciters.defaultReciterId);
      expect(QuranReciters.byId('ar.alafasy').id, 'ar.alafasy');
      expect(QuranReciters.byId('ar.saudalshuraim').englishName, isNotEmpty);
    });

    test('is comprehensive, not a token list', () {
      // The catalogue is generated by tool/build_reciters.py from live CDN
      // evidence. It used to be hand-written and listed only 18 reciters,
      // which silently hid editions the CDN does serve.
      expect(QuranReciters.all.length, greaterThanOrEqualTo(100));
    });

    test('Arabic names are unique after de-duplication', () {
      final names = QuranReciters.all.map((r) => r.arabicName).toList();
      expect(names.toSet().length, names.length);
    });

    test('offers عبد الله المطرود, a reciter the old list omitted', () {
      expect(QuranReciters.isVerified('ar.abdullahalmatrood'), isTrue);
      expect(
        QuranReciters.byId('ar.abdullahalmatrood').arabicName,
        contains('المطرود'),
      );
    });

    test('still excludes the editions the CDN answers 403 for', () {
      for (final id in <String>[
        'ar.husary',
        'ar.husarymujawwad',
        'ar.mahermuaiqly',
        'ar.minshawi',
        'ar.abdurrahmaansudais',
        'ar.hudhaify',
        'ar.alafasy-2',
        'ar.abdulbasitmurattal-surah',
      ]) {
        expect(QuranReciters.isVerified(id), isFalse, reason: id);
      }
    });
  });

  group('QuranReciters.search', () {
    test('an empty query returns the whole catalogue', () {
      expect(QuranReciters.search('').length, QuranReciters.all.length);
      expect(QuranReciters.search('   ').length, QuranReciters.all.length);
    });

    test('finds a reciter by Arabic name', () {
      final hits = QuranReciters.search('المطرود');
      expect(hits.map((r) => r.id), contains('ar.abdullahalmatrood'));
    });

    test('ignores harakat in the query', () {
      expect(
        QuranReciters.search('العفاسي').map((r) => r.id),
        contains('ar.alafasy'),
      );
    });

    test('finds a reciter by Latin name or identifier', () {
      expect(
        QuranReciters.search('matrood').map((r) => r.id),
        contains('ar.abdullahalmatrood'),
      );
      expect(
        QuranReciters.search('ar.alafasy').map((r) => r.id),
        contains('ar.alafasy'),
      );
    });

    test('returns nothing for a query that matches no reciter', () {
      expect(QuranReciters.search('zzqqxx'), isEmpty);
    });

    test('never returns anything outside the catalogue', () {
      for (final query in <String>['محمد', 'عبد', 'a', 'ar.']) {
        expect(
          QuranReciters.search(query).every(QuranReciters.all.contains),
          isTrue,
          reason: query,
        );
      }
    });
  });

  group('persistence', () {
    late LocalStore store;

    setUp(() async {
      SharedPreferences.setMockInitialValues(<String, Object>{});
      LocalStore.overrideInstance(null);
      store = await LocalStore.instance();
    });

    test('the reciter key is registered for the app-data reset', () {
      expect(LocalStore.allKeys, contains(LocalStore.keyAudioReciter));
    });

    test('defaults to the catalogue default when nothing is stored', () {
      expect(
        SettingsRepository(store).load().reciterId,
        QuranReciters.defaultReciterId,
      );
    });

    test('AppSettings resolves its reciter through the catalogue', () {
      const settings = AppSettings();
      expect(settings.reciter.id, QuranReciters.defaultReciterId);

      final chosen = settings.copyWith(reciterId: 'ar.faresabbad');
      expect(chosen.reciter.id, 'ar.faresabbad');
      expect(chosen.reciter.englishName, contains('Fares'));
    });

    test('round-trips a chosen reciter', () async {
      final repository = SettingsRepository(store);
      await repository.save(
        const AppSettings().copyWith(reciterId: 'ar.saudalshuraim'),
      );

      final reloaded = SettingsRepository(store).load();
      expect(reloaded.reciterId, 'ar.saudalshuraim');
      expect(reloaded.reciter.englishName, contains('Shuraim'));
    });

    test('an unverified stored id falls back instead of breaking playback', () async {
      // Simulate a value persisted by a build that offered a now-403 edition.
      await store.setJson(LocalStore.keySettings, <String, dynamic>{
        'reciterId': 'ar.husary',
      });
      expect(
        SettingsRepository(store).load().reciterId,
        QuranReciters.defaultReciterId,
      );
    });

    test('a missing reciter field keeps the default (older payloads)', () async {
      await store.setJson(LocalStore.keySettings, <String, dynamic>{
        'localeCode': 'en',
      });
      final loaded = SettingsRepository(store).load();
      expect(loaded.localeCode, 'en');
      expect(loaded.reciterId, QuranReciters.defaultReciterId);
    });
  });
}
